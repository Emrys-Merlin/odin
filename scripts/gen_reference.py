"""Generate the parts of the docs reference that the code already describes.

Run after changing the CLI, a chat command or a template placeholder:

    uv run scripts/gen_reference.py

Writes Markdown fragments into docs/reference/_generated/, which the reference pages include
with `--8<--`. tests/test_reference_docs.py fails when the committed files are stale.

- cli.md: every `odin` subcommand and option, from the argparse parser in `odin.cli`.
- chat-commands.md: every chat command, from the registry `odin.commands.COMMANDS`, and the
  template names and schedule points its arguments take.
- placeholders.md: every template placeholder, from the data behind `/vars`, with its value in
  config.example.toml.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from odin.cli import _parser
from odin.commands import COMMANDS
from odin.commands.vars import DESCRIPTIONS, _order
from odin.config import TEMPLATE_PLACEHOLDERS, load_config
from odin.overrides import EDITABLE_TEMPLATES, SCHEDULE_POINTS

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "reference" / "_generated"
EXAMPLE_CONFIG = ROOT / "config.example.toml"

HEADER = (
    "<!-- Generated by scripts/gen_reference.py from {source}. Do not edit; "
    "run `uv run scripts/gen_reference.py`. -->\n"
)


def _cell(text: str) -> str:
    """Text for a Markdown table cell: one line, pipes escaped."""
    return " ".join(text.split()).replace("|", "\\|")


def _code(text: str) -> str:
    """A code span for a table cell. Its pipes need no escape: tables skip code spans."""
    return "`" + " ".join(text.split()) + "`"


def _optionals(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [
        action
        for action in parser._actions
        if action.option_strings and not isinstance(action, argparse._HelpAction)
    ]


def _argument(action: argparse.Action) -> str:
    """The value an option takes (``STEP``), or "" for a flag."""
    if action.nargs == 0:
        return ""
    return str(action.metavar or action.dest.upper())


def _synopsis(prog: str, parser: argparse.ArgumentParser) -> str:
    """``odin setup [--status] [--pin] [--redo STEP]`` — built by hand, so it never wraps."""
    parts = [prog]
    for action in _optionals(parser):
        flag = action.option_strings[-1]
        argument = _argument(action)
        parts.append(f"[{flag} {argument}]" if argument else f"[{flag}]")
    return " ".join(parts)


def _options_table(parser: argparse.ArgumentParser) -> list[str]:
    actions = _optionals(parser)
    if not actions:
        return ["No options."]
    lines = ["| Option | Value | Description |", "|---|---|---|"]
    for action in actions:
        flags = ", ".join(f"`{flag}`" for flag in action.option_strings)
        argument = _argument(action)
        value = _code(argument) if argument else "–"
        if action.choices:
            value += " (" + ", ".join(f"`{choice}`" for choice in action.choices) + ")"
        lines.append(f"| {flags} | {value} | {_cell(action.help or '')} |")
    return lines


def render_cli() -> str:
    parser = _parser()
    (subparsers,) = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
    helps = {action.dest: action.help or "" for action in subparsers._choices_actions}
    lines = [
        HEADER.format(source="`_parser()` in src/odin/cli.py"),
        f"{parser.description}",
        "",
        "```",
        f"{parser.prog} [--version] <command> [options]",
        "```",
        "",
        "## Global options",
        "",
        *_options_table(parser),
        "",
        "## Environment",
        "",
        f"{parser.epilog}",
    ]
    for name, sub in subparsers.choices.items():
        lines += [
            "",
            f"## `{parser.prog} {name}`",
            "",
            f"{helps[name][0].upper()}{helps[name][1:]}.",
            "",
            "```",
            _synopsis(f"{parser.prog} {name}", sub),
            "```",
            "",
            *_options_table(sub),
        ]
    return "\n".join(lines) + "\n"


def render_chat_commands() -> str:
    lines = [
        HEADER.format(source="`COMMANDS` in src/odin/commands/__init__.py"),
        "In the order `/help` lists them. Usage and summary are the German texts `/help` shows.",
        "",
        "| Command | Alias | Usage | Summary (as in `/help`) |",
        "|---|---|---|---|",
    ]
    for command in COMMANDS:
        lines.append(
            f"| `/{command.name}` | `!{command.name}` | {_code(command.usage)} "
            f"| {_cell(command.summary)} |"
        )
    lines += [
        "",
        "## Argument values",
        "",
        "`<name>` (`/text`, `/settext`, `/resettext`, `/vars`) is one of the chat-editable "
        "templates: " + ", ".join(f"`{name}`" for name in EDITABLE_TEMPLATES) + ".",
        "",
        "`<punkt>` (`/settime`, `/resettime`) is one of the schedule points, in schedule order: "
        + ", ".join(f"`{point}`" for point in SCHEDULE_POINTS)
        + ".",
    ]
    return "\n".join(lines) + "\n"


def render_placeholders() -> str:
    examples = load_config(EXAMPLE_CONFIG).placeholder_values()
    templates = list(TEMPLATE_PLACEHOLDERS)
    every = frozenset.intersection(*TEMPLATE_PLACEHOLDERS.values())
    names = sorted(frozenset().union(*TEMPLATE_PLACEHOLDERS.values()), key=_order)
    lines = [
        HEADER.format(source="`TEMPLATE_PLACEHOLDERS` in src/odin/config.py and `/vars`"),
        "In the order `/vars` lists them. The description is the German text `/vars` shows; the "
        "example is the value with the schedule of `config.example.toml`.",
        "",
        "| Placeholder | Description (as in `/vars`) | Example | Allowed in |",
        "|---|---|---|---|",
    ]
    for name in names:
        example = _code(examples[name]) if name in examples else "depends on the message"
        allowed = (
            "all templates"
            if name in every
            else ", ".join(f"`{t}`" for t in templates if name in TEMPLATE_PLACEHOLDERS[t])
        )
        lines.append(
            f"| `{{{name}}}` | {_cell(DESCRIPTIONS.get(name, ''))} | {example} | {allowed} |"
        )
    return "\n".join(lines) + "\n"


def render() -> dict[str, str]:
    """File name in `OUT_DIR` -> content."""
    return {
        "cli.md": render_cli(),
        "chat-commands.md": render_chat_commands(),
        "placeholders.md": render_placeholders(),
    }


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in render().items():
        (OUT_DIR / name).write_text(content, encoding="utf-8")
        print(f"wrote {(OUT_DIR / name).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
